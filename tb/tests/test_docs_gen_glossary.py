"""Unit tests for tools/docs/gen_glossary.py."""

import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "tools" / "docs"))

import gen_glossary as gg  # type: ignore[import-not-found]  # noqa: E402  # pylint: disable=import-error

COMMON = REPO / "docs" / "manual" / "common"

GOOD = """\
- term: CDC
  kind: acronym
  expansion: clock domain crossing
  definition: A path between two clock domains.
  glossary: true
- term: Yosys
  kind: tool
  definition: A synthesis tool.
"""


def write(tmp_path: Path, text: str) -> Path:
    """Write a dictionary file."""
    path = tmp_path / "dictionary.yaml"
    path.write_text(text, encoding="utf-8")
    return path


def test_valid_yaml_generates_expected_lines(tmp_path: Path) -> None:
    """Valid YAML generates one line per entry, sorted."""
    out = gg.render(gg.load(write(tmp_path, GOOD)))
    lines = out.splitlines()
    assert lines[0].startswith("% Generated by tools/docs/gen_glossary.py")
    assert lines[1] == (
        "\\newacronym[description={Clock domain crossing. A path between two clock domains.}]"
        "{CDC}{CDC}{clock domain crossing}"
    )
    assert lines[2] == ("\\newglossaryentry{Yosys}{name={Yosys},description={A synthesis tool.}}")
    assert out.endswith("\n") and "\r" not in out


def test_special_characters_are_escaped(tmp_path: Path) -> None:
    """The LaTeX special characters in a definition are escaped."""
    text = GOOD.replace("A synthesis tool.", "'R&D_x 50% #1 $y {z}'")
    out = gg.render(gg.load(write(tmp_path, text)))
    assert "R\\&D\\_x 50\\% \\#1 \\$y \\{z\\}" in out


def test_tex_escape_backslash_and_tilde() -> None:
    """Backslash, tilde and caret use text macros."""
    assert gg.tex_escape("a\\b~c^d") == "a\\textbackslash{}b\\textasciitilde{}c\\textasciicircum{}d"


def test_duplicate_term_rejected(tmp_path: Path) -> None:
    """A duplicate term, also in a different case, is rejected."""
    text = GOOD + GOOD.split("- term: Yosys", maxsplit=1)[0].replace("CDC", "cdc")
    with pytest.raises(gg.SchemaError, match="duplicate"):
        gg.load(write(tmp_path, text))


def test_acronym_without_expansion_rejected(tmp_path: Path) -> None:
    """An acronym needs an expansion."""
    text = GOOD.replace("  expansion: clock domain crossing\n", "")
    with pytest.raises(gg.SchemaError, match="expansion"):
        gg.load(write(tmp_path, text))


def test_unknown_kind_rejected(tmp_path: Path) -> None:
    """An unknown kind is rejected."""
    with pytest.raises(gg.SchemaError, match="kind"):
        gg.load(write(tmp_path, GOOD.replace("kind: tool", "kind: gadget")))


def test_missing_definition_rejected_only_for_glossary_entries(tmp_path: Path) -> None:
    """A definition is required when glossary is true."""
    text = "- term: Foo\n  kind: tool\n"
    with pytest.raises(gg.SchemaError, match="definition"):
        gg.load(write(tmp_path, text))
    entries = gg.load(write(tmp_path, text + "  glossary: false\n"))
    assert gg.render(entries).splitlines() == [gg.HEADER.rstrip("\n")]


def test_sorted_case_insensitively(tmp_path: Path) -> None:
    """Entries are sorted without regard to case."""
    text = (
        "- term: zeta\n  kind: tool\n  definition: Z.\n"
        "- term: Alpha\n  kind: tool\n  definition: A.\n"
        "- term: beta\n  kind: tool\n  definition: B.\n"
    )
    out = gg.render(gg.load(write(tmp_path, text)))
    names = [ln.split("{")[1].split("}")[0] for ln in out.splitlines()[1:]]
    assert names == ["Alpha", "beta", "zeta"]


def test_check_detects_drift_and_passes_when_in_sync(tmp_path: Path) -> None:
    """--check fails for a stale file and passes after a write."""
    dic = write(tmp_path, GOOD)
    out = tmp_path / "glossary.tex"
    args = ["--dictionary", str(dic), "--output", str(out)]
    assert gg.main([*args, "--check"]) == 1
    assert gg.main(args) == 0
    assert gg.main([*args, "--check"]) == 0
    out.write_bytes(out.read_bytes() + b"% drift\n")
    assert gg.main([*args, "--check"]) == 1


def test_invalid_yaml_exits_2(tmp_path: Path) -> None:
    """Broken YAML and schema errors give exit code 2."""
    dic = write(tmp_path, "- term: [unclosed\n")
    assert gg.main(["--dictionary", str(dic), "--output", str(tmp_path / "g.tex")]) == 2
    dic = write(tmp_path, "term: not-a-list\n")
    assert gg.main(["--dictionary", str(dic), "--output", str(tmp_path / "g.tex")]) == 2


def test_committed_glossary_is_in_sync() -> None:
    """The committed glossary.tex matches the committed dictionary.yaml."""
    assert gg.main(["--check"]) == 0


def test_committed_dictionary_has_required_acronyms() -> None:
    """The seed acronyms and tools are present."""
    terms = {e["term"] for e in gg.load(COMMON / "dictionary.yaml")}
    assert {"CDC", "STA", "MMIO", "Verilator", "Sky130", "ASAP7"} <= terms
