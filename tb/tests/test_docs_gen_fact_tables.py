def test_code_helper_rejects_backslash_hash_and_unbalanced_braces() -> None:
    """The code helper refuses what TeX cannot take safely."""
    for text in ("a%b", "a#b", "a\\b", "{a", "a}"):
        with pytest.raises(gft.FactError):
            gft.code(text)
    assert gft.code("{4'h1,4'h2}") == "\\code{{4'h1,4'h2}}"


