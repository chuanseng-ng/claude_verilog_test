def sidecar(module: str, params: dict[str, str], ports: dict[str, str]) -> str:
    """Return the text of a sidecar file for one module. A port value is its domain."""
    lines = [f"family: demo\nmodules:\n  {module}:\n    rtl: rtl/{module}.sv\n"]
    lines.append(f"    label: tm:mod:{module}\n    params:\n")
    lines += [f'      {n}: {{legal: "any", description: "{d}"}}\n' for n, d in params.items()]
    lines.append("    ports:\n")
    lines += [f'      {n}: {{domain: {d}, description: "Text."}}\n' for n, d in ports.items()]
    return "".join(lines)


def one_module(root: Path, module: str, sv: str, params: dict[str, str], ports: dict[str, str]):  # type: ignore[no-untyped-def]
    """Create a root with one module and its sidecar file."""
    make_root(root, yaml_text=sidecar(module, params, ports))
    (root / f"rtl/{module}.sv").write_text(sv, encoding="utf-8", newline="\n")
    return root


def signal_rows(root: Path, module: str) -> dict[str, str]:
    """Return the rows of a signal table by port name."""
    text = (out_dir(root) / f"{module}-signals.tex").read_text(encoding="utf-8")
    return {ln.split(" & ")[0]: ln for ln in text.splitlines() if ln.startswith("\\code{")}


def test_ports_that_share_a_declaration_keep_the_width(tmp_path) -> None:  # type: ignore[no-untyped-def]
    """The second port of 'input logic [W-1:0] a_i, b_i' has the width of the first."""
    sv = (
        "module wide #(parameter int W = 8) (\n"
        "    input logic clk_i,\n    input logic [W-1:0] a_i, b_i,\n    output logic q_o\n);\n"
        "endmodule\n"
    )
    ports = {"clk_i": "clock", "a_i": "async", "b_i": "async", "q_o": "clk_i"}
    root = one_module(tmp_path, "wide", sv, {"W": "Width."}, ports)
    assert run(root) == 0
    rows = signal_rows(root, "wide")
    assert rows["\\code{a_i}"] == "\\code{a_i} & in & \\code{W} (8) & async & Text.\\\\"
    assert rows["\\code{b_i}"] == "\\code{b_i} & in & \\code{W} (8) & async & Text.\\\\"


def test_packed_array_of_a_typedef_shows_the_real_width(tmp_path) -> None:  # type: ignore[no-untyped-def]
    """A packed array of a typedef is not a bare dimension count."""
    sv = (
        "typedef logic [7:0] byte_t;\n"
        "module arr (input logic clk_i, input byte_t [1:0] w_i);\nendmodule\n"
    )
    root = one_module(tmp_path, "arr", sv, {}, {"clk_i": "clock", "w_i": "async"})
    assert run(root) == 0
    row = signal_rows(root, "arr")["\\code{w_i}"]
    assert row.startswith("\\code{w_i} & in & \\code{byte_t [1:0]} (16) &")


def test_range_text_and_elaborated_width_must_agree() -> None:
    """A literal range that disagrees with the elaborated width names the port and stops."""
    written = gft.ModuleFacts("m", ports=[gft.Port("a_i", "input", "logic [7:0]", ["7:0"])])
    built = gft.ModuleFacts("m", ports=[gft.Port("a_i", "in", "", [], 4)])
    with pytest.raises(gft.FactError, match="port a_i: the declared range gives 8 bits"):
        gft.merge(written, built)


def test_expression_range_is_checked_with_the_parameters() -> None:
    """A range of parameters is evaluated with the elaborated values."""
    written = gft.ModuleFacts("m", ports=[gft.Port("a_i", "input", "logic [W*2-1:0]", ["W*2-1:0"])])
    built = gft.ModuleFacts("m", ports=[gft.Port("a_i", "in", "", [], 9)], env={"W": 4})
    with pytest.raises(gft.FactError, match="gives 8 bits and elaboration gives 9"):
        gft.merge(written, built)


def test_the_two_passes_must_list_the_same_ports_and_parameters() -> None:
    """A port or parameter that only one pass finds stops the tool."""
    one = gft.ModuleFacts("m", ports=[gft.Port("a_i", "input", "logic", [])])
    two = gft.ModuleFacts(
        "m", ports=[gft.Port("a_i", "in", "", [], 1), gft.Port("b_i", "in", "", [], 1)]
    )
    with pytest.raises(gft.FactError, match="port lists of the two passes differ"):
        gft.merge(one, two)
    p_one = gft.ModuleFacts("m", params=[gft.Param("P", "int", "1")])
    with pytest.raises(gft.FactError, match="parameter lists of the two passes differ"):
        gft.merge(p_one, gft.ModuleFacts("m"))


