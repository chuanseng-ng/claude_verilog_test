def test_description_escaping_and_code_spans(tmp_path) -> None:  # type: ignore[no-untyped-def]
    """Special characters are escaped in text. A backtick span becomes code."""
    root = make_root(tmp_path)
    assert run(root) == 0
    par = (out_dir(root) / "widget-params.tex").read_text(encoding="utf-8")
    assert "Bits of \\code{d_i} \\& more\\_text." in par
    assert gft.tex_escape("a_b%c#d$e{f}g~h^i\\j&k") == (
        "a\\_b\\%c\\#d\\$e\\{f\\}g\\textasciitilde{}h\\textasciicircum{}i\\textbackslash{}j\\&k"
    )


