def test_check_passes_on_fresh_output_and_fails_on_one_byte(tmp_path, capsys) -> None:  # type: ignore[no-untyped-def]
    """The check is clean after a write and fails after one changed byte."""
    root = make_root(tmp_path)
    assert run(root) == 0
    assert run(root, "--check") == 0
    path = out_dir(root) / "widget-signals.tex"
    data = bytearray(path.read_bytes())
    data[-3] ^= 1
    path.write_bytes(bytes(data))
    capsys.readouterr()
    assert run(root, "--check") == 1
    assert "widget-signals.tex is out of date" in capsys.readouterr().out


