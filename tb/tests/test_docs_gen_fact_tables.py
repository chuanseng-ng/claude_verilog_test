sys.path.insert(0, str(REPO / "tools" / "docs"))

import gen_fact_tables as gft  # type: ignore[import-not-found]  # noqa: E402  # pylint: disable=import-error

GOOD_SV = """\
module widget #(
    parameter int unsigned WIDTH = 1,
    parameter int unsigned DEPTH = WIDTH * 4
) (
    input  logic             clk_i,
    input  logic [WIDTH-1:0] d_i,
    output logic [7:0]       q_o
);
    assign q_o = '0;
endmodule
"""

NON_ANSI_SV = """\
module oldstyle (clk_i, q_o);
    input clk_i;
    output q_o;
endmodule
"""

GOOD_YAML = """\
family: demo
modules:
  widget:
    rtl: rtl/widget.sv
    label: tm:mod:widget
    params:
      WIDTH: {legal: ">= 1", description: "Bits of `d_i` & more_text."}
      DEPTH: {legal: "any", description: "Depth."}
    ports:
      clk_i: {domain: clock, description: "Clock."}
      d_i: {domain: async, description: "Input."}
      q_o: {domain: clk_i, description: "Output."}
"""


def make_root(root: Path, sv: str = GOOD_SV, yaml_text: str = GOOD_YAML) -> Path:
    """Create a synthetic repository with one module and one sidecar file."""
    files = {
        "rtl/widget.sv": sv,
        "rtl/oldstyle.sv": NON_ANSI_SV,
        "docs/manual/common/facts/demo.yaml": yaml_text,
    }
    for name, text in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    return root


def out_dir(root: Path) -> Path:
    """Return the directory of the generated files."""
    return root / "docs/manual/common/generated/facts"


def run(root: Path, *extra: str) -> int:
    """Run the generator on a synthetic root."""
    return int(gft.main(["--root", str(root), *extra]))


def test_ansi_module_renders_expected_rows(tmp_path) -> None:  # type: ignore[no-untyped-def]
    """Ports and parameters appear in RTL order with width, default and domain."""
    root = make_root(tmp_path)
    assert run(root) == 0
    sig = (out_dir(root) / "widget-signals.tex").read_text(encoding="utf-8")
    par = (out_dir(root) / "widget-params.tex").read_text(encoding="utf-8")
    assert sig.startswith(
        "% Generated by tools/docs/gen_fact_tables.py from rtl/widget.sv "
        "and docs/manual/common/facts/demo.yaml. Do not edit.\n"
    )
    assert "\\label{tab:tm:mod:widget:signals}" in sig
    assert "\\caption{Signals of \\code{widget}}" in sig
    assert "Signal & Dir & Width & Clock domain & Description" in sig
    rows = [ln for ln in sig.splitlines() if ln.startswith("\\code{")]
    assert [r.split(" & ")[0] for r in rows] == ["\\code{clk_i}", "\\code{d_i}", "\\code{q_o}"]
    assert rows[0] == "\\code{clk_i} & in & 1 & clock & Clock.\\\\"
    assert rows[2] == "\\code{q_o} & out & 8 & \\code{clk_i} & Output.\\\\"
    assert "\\label{tab:tm:mod:widget:params}" in par
    assert "\\code{DEPTH} & \\code{int unsigned} & \\code{WIDTH * 4} (\\code{4}) & any" in par


