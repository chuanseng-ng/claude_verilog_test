# --------------------------------------------------------------------------------------------
# BLOCK MODE (bead claude_verilog_test-j41m.4): the CPU hard macro
# --------------------------------------------------------------------------------------------
# A miniature of rv32i_cpu_top: its flops are clocked straight from the clk_i pin (the parent muxes
# the test clock onto it), reset is synchronous, and in the ASAP7 arm a clock-gate latch whose
# enable carries test_en (= scan_mode_i) clocks a memory. The checker must accept exactly that and
# reject each way of breaking it.
_BLK_HEAD = """
module top (
    input  wire clk_i, input wire rst_ni, input wire scan_mode_i, input wire d, input wire en_i,
    output reg  q, output wire gclk_o
);
    always @(posedge clk_i) if (!rst_ni) q <= 1'b0; else q <= d;
"""
_BLK_GATE_TESTEN = """
    reg en_l;
    always @* if (!clk_i) en_l = en_i | scan_mode_i;
    assign gclk_o = clk_i & en_l;
endmodule
"""
_BLK_GATE_NOTEST = """
    reg en_l;
    always @* if (!clk_i) en_l = en_i;
    assign gclk_o = clk_i & en_l;
endmodule
"""
_BLK_ARGS = ("--clock-port", "clk_i", "--max-async-pins", "0", "--expect-seq-min", "2",
             "--all-latches-need-scan-mode", "--expect-latches-min", "1")


def _blk_run(tmp_path: Path, tail: str, head: str = _BLK_HEAD, args: tuple = _BLK_ARGS):
    netlist = tmp_path / "top.v"
    netlist.write_text(head + tail)
    env = dict(os.environ, YOSYS=str(YOSYS))
    return subprocess.run(
        [sys.executable, str(CHECKER), "--netlist", str(netlist), "--top", "top", *args],
        capture_output=True,
        text=True,
        env=env,
        check=False,
    )


def test_block_mode_clock_pin_and_test_en_gate_pass(tmp_path: Path) -> None:
    res = _blk_run(tmp_path, _BLK_GATE_TESTEN)
    assert res.returncode == 0, res.stdout
    assert "violations: 0" in res.stdout


def test_block_mode_requires_the_clock_port_declaration(tmp_path: Path) -> None:
    # without --clock-port the same netlist is the un-muxed-clock violation of the SoC-level rule
    res = _blk_run(tmp_path, _BLK_GATE_TESTEN, args=("--max-async-pins", "0"))
    assert res.returncode == 1, res.stdout
    assert "without a scan-mode mux" in res.stdout


def test_block_mode_gate_without_test_term_fails(tmp_path: Path) -> None:
    # the j41m.2 state of the cache gates: test_en tied 0 -> the latch enable has no scan_mode term
    res = _blk_run(tmp_path, _BLK_GATE_NOTEST)
    assert res.returncode == 1, res.stdout
    assert "no scan-mode term in its D input" in res.stdout


def test_block_mode_async_reset_trips_max_async_pins(tmp_path: Path) -> None:
    head = _BLK_HEAD.replace(
        "always @(posedge clk_i) if (!rst_ni) q <= 1'b0; else q <= d;",
        "always @(posedge clk_i or negedge rst_ni) if (!rst_ni) q <= 1'b0; else q <= d;",
    )
    res = _blk_run(tmp_path, _BLK_GATE_TESTEN, head=head)
    assert res.returncode == 1, res.stdout
    assert "at most 0 async reset/set pins" in res.stdout


def test_block_mode_flop_generated_clock_still_fails(tmp_path: Path) -> None:
    tail = _BLK_GATE_TESTEN.replace(
        "endmodule", "    reg dv_q;\n    always @(posedge clk_i) dv_q <= d;\n    reg r_q;\n"
        "    always @(posedge dv_q) r_q <= d;\n    assign gclk_o = gclk_o2 & r_q;\n    wire gclk_o2 = clk_i;\nendmodule"
    ).replace("    assign gclk_o = clk_i & en_l;\n", "")
    res = _blk_run(tmp_path, tail)
    assert res.returncode == 1, res.stdout
    assert "generated by sequential cell" in res.stdout


def test_block_mode_latch_count_guard(tmp_path: Path) -> None:
    # all gates removed: nothing left to check, which must not read as a pass
    res = _blk_run(tmp_path, "    assign gclk_o = clk_i;\nendmodule\n")
    assert res.returncode == 1, res.stdout
    assert "expected at least 1 latches" in res.stdout


def test_block_mode_seq_min_guard(tmp_path: Path) -> None:
    res = _blk_run(tmp_path, _BLK_GATE_TESTEN, args=("--clock-port", "clk_i", "--expect-seq-min", "50"))
    assert res.returncode == 1, res.stdout
    assert "expected at least 50 sequential cells" in res.stdout
