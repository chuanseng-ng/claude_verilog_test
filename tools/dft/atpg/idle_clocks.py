#!/usr/bin/env python3
"""Force the clock inputs of Quaigh patterns to their idle value 0.

usage: idle_clocks.py --map map.json --patterns P.test --out P0.test [--first N]

A Quaigh pattern assigns a value to every cut input, the clock inputs included.  The tester
cannot hold a clock at 1 while it compares the outputs: a clock is low until its capture pulse.
A primary output that depends on a clock input (here the clock pins of the black-boxed SRAMs)
is then expected at the value for clock = 0.  This tool writes the patterns with the
`kind: clock` inputs of the plan cleared; `quaigh simulate --expose-ff` on the result gives the
expected responses.  Run it before `quaigh simulate` and `replay_vectors.py`; both must see
the same file.
"""

import argparse
import json
from pathlib import Path


def clock_indices(plan):
    return [i for i, x in enumerate(plan["inputs"]) if x["kind"] == "clock"]


def clear_bits(bits, idx):
    out = list(bits)
    for i in idx:
        out[i] = "0"
    return "".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--map", required=True)
    ap.add_argument("--patterns", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--first", type=int, help="keep only the first N patterns")
    a = ap.parse_args(argv)
    idx = clock_indices(json.loads(Path(a.map).read_text()))
    lines = ["* Test pattern file", "* generated by quaigh, clock inputs idle (idle_clocks.py)"]
    kept = 0
    for ln in Path(a.patterns).read_text().splitlines():
        if not ln or ln[0] == "*":
            continue
        if a.first and kept >= a.first:
            break
        n, bits = ln.split(": ")
        lines.append(f"{n}: {clear_bits(bits.strip(), idx)}")
        kept += 1
    Path(a.out).write_text("\n".join(lines) + "\n")
    print(json.dumps({"patterns": kept, "clock_inputs": idx}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
