#!/usr/bin/env python3
"""Seeded random scan patterns in the Quaigh `.test` format.

usage: random_patterns.py --map map.json --count N [--seed S] --out P.test

One line per pattern, `<n>: <bits>`, the bits being the cut inputs followed by the exposed
flop states: the layout `quaigh atpg` writes and `quaigh simulate --expose-ff` reads.  The
width comes from the plan of `pattern_map.py` (inputs plus latches).  The patterns come from a
seeded PRNG and not from Quaigh's search, so they exercise the replay path (good-machine
agreement) without claiming any fault coverage.
"""

import argparse
import json
import random
from pathlib import Path

HEADER = "* Test pattern file\n* generated by random_patterns.py\n"


def width_of(plan):
    return len(plan["inputs"]) + len(plan["latches"])


def make_patterns(width, count, seed):
    if width <= 0 or count <= 0:
        raise ValueError("width and count must be positive")
    rng = random.Random(seed)
    return ["".join("01"[rng.getrandbits(1)] for _ in range(width)) for _ in range(count)]


def write_patterns(path, pats):
    lines = [f"{i + 1}: {p}" for i, p in enumerate(pats)]
    Path(path).write_text(HEADER + "\n".join(lines) + "\n")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--map", required=True)
    ap.add_argument("--count", type=int, required=True)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    plan = json.loads(Path(a.map).read_text())
    pats = make_patterns(width_of(plan), a.count, a.seed)
    write_patterns(a.out, pats)
    print(json.dumps({"patterns": a.count, "width": width_of(plan), "seed": a.seed}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
