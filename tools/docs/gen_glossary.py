#!/usr/bin/env python3
"""Generate the LaTeX glossary from the project dictionary.

Reads docs/manual/common/dictionary.yaml, validates it and writes
docs/manual/common/glossary.tex as \\newacronym and \\newglossaryentry lines
for glossaries-extra. Entries with ``glossary: false`` are not written.

Usage:
    python tools/docs/gen_glossary.py            write glossary.tex
    python tools/docs/gen_glossary.py --check    fail if the file is stale

Exit codes:
    0  success, or the file is in sync with --check
    1  --check found a difference
    2  the YAML is invalid or does not match the schema
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
COMMON = REPO / "docs" / "manual" / "common"
KINDS = ("acronym", "technical-name", "technical-verb", "tool", "pdk")
TERM_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9 +._-]*$")
HEADER = "% Generated by tools/docs/gen_glossary.py from dictionary.yaml. Do not edit.\n"
_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


class SchemaError(ValueError):
    """The dictionary does not follow the schema."""


def tex_escape(text: str) -> str:
    """Escape the LaTeX special characters of a plain text."""
    return "".join(_ESCAPES.get(c, c) for c in text)


def load(path: Path) -> list[dict]:
    """Load and validate the dictionary. Raise SchemaError on a problem."""
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (yaml.YAMLError, OSError) as exc:
        raise SchemaError(f"{path}: {exc}") from exc
    if data is None:
        data = []
    if not isinstance(data, list):
        raise SchemaError("the top level must be a list of entries")
    seen: set[str] = set()
    for i, entry in enumerate(data, 1):
        if not isinstance(entry, dict):
            raise SchemaError(f"entry {i}: must be a mapping")
        term = entry.get("term")
        if not isinstance(term, str) or not TERM_RE.match(term):
            raise SchemaError(f"entry {i}: invalid term {term!r}")
        if term.casefold() in seen:
            raise SchemaError(f"duplicate term {term!r}")
        seen.add(term.casefold())
        if entry.get("kind") not in KINDS:
            raise SchemaError(f"{term}: unknown kind {entry.get('kind')!r}")
        if not isinstance(entry.get("glossary", True), bool):
            raise SchemaError(f"{term}: glossary must be true or false")
        if entry["kind"] == "acronym" and not str(entry.get("expansion") or "").strip():
            raise SchemaError(f"{term}: an acronym needs an expansion")
        if entry.get("glossary", True) and not str(entry.get("definition") or "").strip():
            raise SchemaError(f"{term}: a glossary entry needs a definition")
    return data


def render(entries: list[dict]) -> str:
    """Return the text of glossary.tex."""
    lines = [HEADER.rstrip("\n")]
    for e in sorted(entries, key=lambda x: (x["term"].casefold(), x["term"])):
        if not e.get("glossary", True):
            continue
        label = e["term"].replace(" ", "-")
        name = tex_escape(e["term"])
        definition = tex_escape(str(e["definition"]).strip())
        if e["kind"] == "acronym":
            raw = str(e["expansion"]).strip()
            expansion = tex_escape(raw)
            full = tex_escape(raw[0].upper() + raw[1:]) + ". " + definition
            lines.append(
                f"\\newacronym[description={{{full}}}]{{{label}}}{{{name}}}{{{expansion}}}"
            )
        else:
            lines.append(
                f"\\newglossaryentry{{{label}}}{{name={{{name}}},description={{{definition}}}}}"
            )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Run the command line tool."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if glossary.tex is stale")
    ap.add_argument("--dictionary", type=Path, default=COMMON / "dictionary.yaml")
    ap.add_argument("--output", type=Path, default=COMMON / "glossary.tex")
    args = ap.parse_args(argv)
    try:
        text = render(load(args.dictionary))
    except SchemaError as exc:
        print(f"gen_glossary: error: {exc}", file=sys.stderr)
        return 2
    data = text.encode("utf-8")
    if args.check:
        # A Windows checkout can hold CRLF; line endings are not drift.
        current = args.output.read_bytes().replace(b"\r\n", b"\n") if args.output.exists() else None
        if current != data:
            print(f"gen_glossary: {args.output} is out of date; run gen_glossary.py")
            return 1
        print("gen_glossary: glossary.tex is in sync")
        return 0
    args.output.write_bytes(data)
    print(f"gen_glossary: wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
