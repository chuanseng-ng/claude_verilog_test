"""Project-local LibreLane plugin for the Sky130 CPU macro OpenROAD generation B3 (commercial-flow comparison step 9).

``CVTClassicB3`` = the stock ``Classic`` flow plus ``CVT.InsertDout0Buffers`` (InsertECOBuffers minus the incremental GRT) right after ``OpenROAD.DetailedPlacement``
(the SRAM dout0 max-cap buffers, driver-side, each placed next to its SRAM pin; the list is ``INSERT_ECO_BUFFERS`` in
``config_b3.json``, generated by ``gen_b3_config.py``).  Nothing else differs from Classic, so the B2 flow is otherwise reproduced.
LibreLane imports every ``librelane_plugin_*`` module on PYTHONPATH at start-up (librelane/plugins.py).
"""
from librelane.flows import Flow
from librelane.flows.classic import Classic
import os

from librelane.steps import Odb, OpenROAD
from librelane.steps.step import Step


@Step.factory.register()
class CVTInsertDout0Buffers(Odb.InsertECOBuffers):
    """Odb.InsertECOBuffers without the incremental global route (see dout0_buffers.py): same config (INSERT_ECO_BUFFERS)."""

    id = "CVT.InsertDout0Buffers"
    name = "Insert dout0 buffers (no GRT)"

    def get_script_path(self):
        return os.path.join(os.path.dirname(os.path.abspath(__file__)), "dout0_buffers.py")


def _steps() -> list:
    steps = list(Classic.Steps)
    idx = steps.index(OpenROAD.DetailedPlacement)
    return steps[: idx + 1] + [CVTInsertDout0Buffers] + steps[idx + 1 :]


@Flow.factory.register()
class CVTClassicB3(Classic):
    """Classic + dout0 ECO buffers after detailed placement."""

    Steps = _steps()
