#!/usr/bin/env python3
"""gen_iolat_sdc.py -- write sky130_cpu_iolat.sdc from the shared SDC (COMPARISON ONLY).

Usage (any cwd):  python3 -I pnr/commercial/constraints/gen_iolat_sdc.py
Source  : pnr/sky130/cpu/constraints/sky130_cpu.sdc   (md5 must be 3c69635042a9d65cb87e71a9db713e4e; fails otherwise)
Output  : pnr/commercial/constraints/sky130_cpu_iolat.sdc  and  sky130_cpu_iolat.sdc.md5 (md5 of the full output file)
The source SDC is never modified: the production LibreLane CPU-macro flow uses it.
Deterministic: no timestamps.
"""
import hashlib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "../../.."))
SRC = os.path.join(ROOT, "pnr/sky130/cpu/constraints/sky130_cpu.sdc")
OUT = os.path.join(HERE, "sky130_cpu_iolat.sdc")
SRC_MD5 = "3c69635042a9d65cb87e71a9db713e4e"
IO_LATENCY_NS = "1.778"
MD5_TAG = "# GENERATED_MD5_EXCL_THIS_LINE: "

HEADER = """\
#=============================================================================
# sky130_cpu_iolat.sdc -- COMPARISON-ONLY variant of sky130_cpu.sdc with an I/O clock latency.
# GENERATED by pnr/commercial/constraints/gen_iolat_sdc.py -- do not edit by hand.
# Source: pnr/sky130/cpu/constraints/sky130_cpu.sdc, md5 3c69635042a9d65cb87e71a9db713e4e (asserted by the generator).
#         The source file is NOT modified: the production LibreLane CPU-macro flow uses it.
#
# WHY.  ICC2's own SDC (impl/icc2/runs/b5a_icc2/out/rv32i_cpu_top.sdc) carried
#         set_clock_latency 1.77814 [get_clocks clk_i]   ("Set latency for io paths", -origin useful_skew)
#       which the shared SDC does not.  Without it, input ports launch at 1.0 ns (source latency) + the input delay
#       against a capture clock arriving ~2.7 ns after the CTS tree, and ICC2's I/O hold looks 1.2 ns worse in the neutral judge
#       than in ICC2's own run (pt_judge_summary.md section 5.2).  This file models that I/O latency as a VIRTUAL clock.
# ASSUMPTION.  The SoC-side flops that drive/capture the macro's ports have about the same insertion delay as the macro's
#       internal flops, so the I/O clock arrives 1.778 ns after its source (ICC2's derived value, rounded).
# WHAT CHANGES.  A virtual clock clk_io (period 13.333, source latency 1.0 mirroring clk_i, network latency 1.778, uncertainty 0.5/0.2
#       as clk_i) is added after the clk_i block; every set_input_delay / set_output_delay is re-referenced from clk_i to clk_io;
#       group_path IO is added for paths from/to clk_io (I/O paths leave the clk_i->clk_i PIPELINE group).  Everything else
#       (false paths, multicycles, drive/load, DRC limits, clk_i itself) is unchanged, so clk_i->clk_i (PIPELINE) results are identical.
# JUDGE NOTE.  clk_io is a virtual, IDEAL clock: only clk_i may be propagated (set_propagated_clock [get_clocks clk_i]); a
#       propagated virtual clock would ignore its network latency.
# COMPARISON ONLY.  Not for signoff, not for the production flow.  OpenROAD and Innovus were implemented against the base SDC,
#       ICC2 effectively against this latency; neither variant is perfectly fair to every arm, so report both.
"""


def main():
    raw = open(SRC, "rb").read()
    md5 = hashlib.md5(raw).hexdigest()
    if md5 != SRC_MD5:
        sys.exit(f"FATAL: source SDC md5 {md5} != expected {SRC_MD5}; refusing to generate")
    lines = raw.decode().splitlines()

    out = []
    n_in = n_out = 0
    inserted_clk = inserted_grp = False
    pat_io = re.compile(r"^(set_input_delay|set_output_delay)(\s+)-clock\s+clk_i\b")
    total_io = sum(1 for l in lines if re.match(r"^(set_input_delay|set_output_delay)\b", l))
    for line in lines:
        m = pat_io.match(line)
        if m:
            line = line.replace("-clock clk_i", "-clock clk_io", 1)
            if m.group(1) == "set_input_delay":
                n_in += 1
            else:
                n_out += 1
        out.append(line)
        if line.strip() == "set_clock_latency -source 1.0 [get_clocks clk_i]":
            assert not inserted_clk
            out += [
                "",
                "# --- I/O clock (comparison only): virtual clock, no source object ------------------------------",
                "create_clock -name clk_io -period 13.333",
                "set_clock_latency -source 1.0 [get_clocks clk_io]",
                f"set_clock_latency {IO_LATENCY_NS} [get_clocks clk_io]",
                "set_clock_uncertainty        0.5 [get_clocks clk_io]",
                "set_clock_uncertainty -hold  0.2 [get_clocks clk_io]",
            ]
            inserted_clk = True
        if line.strip() == "group_path -name PIPELINE -from [get_clocks clk_i] -to [get_clocks clk_i]":
            assert not inserted_grp
            out += [
                "# I/O paths leave the clk_i->clk_i group (comparison variant)",
                "group_path -name IO -from [get_clocks clk_io]",
                "group_path -name IO -to   [get_clocks clk_io]",
            ]
            inserted_grp = True
    assert inserted_clk, "anchor 'set_clock_latency -source 1.0 [get_clocks clk_i]' not found"
    assert inserted_grp, "anchor group_path PIPELINE not found"
    # every I/O delay rewritten
    assert total_io == n_in + n_out, f"I/O delay lines {total_io} != rewritten {n_in + n_out}"
    left = [l for l in out if re.match(r"^set_(input|output)_delay\b", l) and "-clock clk_i " in l + " "]
    assert not left, f"un-rewritten I/O delays: {left[:3]}"
    assert n_in == 28 and n_out == 38, f"unexpected counts in={n_in} out={n_out} (source SDC changed?)"

    body = "\n".join(out) + "\n"
    # self-referential md5: the header states the md5 of the file with the MD5 line removed; the full-file md5 goes to the sidecar
    def render(tag_md5):
        hdr = HEADER + f"{MD5_TAG}{tag_md5}\n" + (f"# rewritten I/O delays: {n_in} set_input_delay + {n_out} set_output_delay (all of them)\n"
                                                    f"#=============================================================================\n\n")
        return hdr + body
    body_wo = render("")  # placeholder, then drop the tag line to hash
    wo_line = "\n".join(l for l in body_wo.splitlines() if not l.startswith(MD5_TAG)) + "\n"
    excl_md5 = hashlib.md5(wo_line.encode()).hexdigest()
    final = render(excl_md5)
    with open(OUT, "w") as f:
        f.write(final)
    full = hashlib.md5(final.encode()).hexdigest()
    with open(OUT + ".md5", "w") as f:
        f.write(full + "\n")
    print(f"wrote {OUT}")
    print(f"rewritten: {n_in} set_input_delay + {n_out} set_output_delay (of {total_io})")
    print(f"md5 (full file, sidecar .md5): {full}")
    print(f"md5 (file without the {MD5_TAG.strip()} line, stated in the header): {excl_md5}")


if __name__ == "__main__":
    main()
