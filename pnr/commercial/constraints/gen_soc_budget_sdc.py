#!/usr/bin/env python3
"""gen_soc_budget_sdc.py -- write sky130_cpu_iolat_pv_soc.sdc from sky130_cpu_iolat_pv.sdc (COMPARISON ONLY, step 4b).

Usage (any cwd):  python3 -I pnr/commercial/constraints/gen_soc_budget_sdc.py
Source : pnr/commercial/constraints/sky130_cpu_iolat_pv.sdc  (full-file md5 must be 57e67934c24b53f40489ad30eeb3c1cf; fails otherwise)
Output : pnr/commercial/constraints/sky130_cpu_iolat_pv_soc.sdc  and  .sdc.md5 (md5 of the full output file)
Neither the source SDC, sky130_cpu_iolat.sdc nor the shared base SDC is modified.

The ONLY change vs the per-view iolat SDC: the 14 `set_input_delay -max` groups (the numeric 2.0 / 3.5 ns) take their value from a table
(env IOBUD_TABLE, tab-separated: rc lib group max_delay_ns), row key = the rc_lib suffix of IOLAT_PV_KEY.  A missing row or group is an error,
never a default.  `-min` input delays, every output delay, the multicycle / false-path lines and the clk_io latency (per-view table) are
unchanged.  ONE file for every arm and corner; only the table differs.  No multicycle, no false path is added.  Deterministic: no timestamps.
"""
import hashlib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "sky130_cpu_iolat_pv.sdc")
OUT = os.path.join(HERE, "sky130_cpu_iolat_pv_soc.sdc")
SRC_MD5 = "57e67934c24b53f40489ad30eeb3c1cf"
MD5_TAG = "# GENERATED_MD5_EXCL_THIS_LINE: "

# port pattern in the source SDC -> budget group name
GROUPS = [
    ("axi_awready_i", "awready"), ("axi_wready_i", "wready"), ("axi_arready_i", "arready"),
    ("axi_bresp_i", "bresp"), ("axi_bvalid_i", "bvalid"),
    ("{axi_rdata_i[*]}", "rdata"), ("{axi_rresp_i[*]}", "rresp"), ("axi_rvalid_i", "rvalid"), ("axi_rlast_i", "rlast"),
    ("{apb_paddr_i[*]}", "paddr"), ("apb_psel_i", "psel"), ("apb_penable_i", "penable"), ("apb_pwrite_i", "pwrite"),
    ("{apb_pwdata_i[*]}", "pwdata"),
]
GNAMES = [g for _, g in GROUPS]

HEADER = """\
#=============================================================================
# sky130_cpu_iolat_pv_soc.sdc -- COMPARISON-ONLY variant of sky130_cpu_iolat_pv.sdc with SoC-CONTEXT INPUT-DELAY BUDGETS (step 4b).
# GENERATED by pnr/commercial/constraints/gen_soc_budget_sdc.py -- do not edit by hand.
# Source: pnr/commercial/constraints/sky130_cpu_iolat_pv.sdc, md5 57e67934c24b53f40489ad30eeb3c1cf (asserted by the generator).
#         That file, sky130_cpu_iolat.sdc and the shared base SDC (3c69635042a9d65cb87e71a9db713e4e) are NOT modified.
#
# WHAT CHANGES.  The 14 `set_input_delay -max` groups (2.0 ns AXI, 3.5 ns APB in the source) take their value per corner and per group from a table:
#         IOBUD_TABLE = tab-separated file  rc <TAB> lib <TAB> group <TAB> max_delay_ns   ('#' lines ignored)
#         row key = the rc_lib suffix of IOLAT_PV_KEY (e.g. icc2b9_max_ss -> max_ss).  A missing row or group is an error, never a default.
#         The applied values are echoed as 'IOBUD key=<rc_lib> awready=.. wready=.. ...' (PrimeTime log) and checked by the runner.
#       Everything else is identical to sky130_cpu_iolat_pv.sdc: clk_io per-view latency (IOLAT_PV_TABLE), -min input delays, all output
#       delays, the existing multicycle / false-path lines, drive / load, DRC limits.  NO multicycle and NO false path is added.
# COMPARISON ONLY.  Not for signoff, not for the production flow.
#=============================================================================
"""

BUD_BLOCK = """\

# --- SoC-context input-delay budgets (step 4b): per rc_lib, per group, from a table -------------------------------
set _bud_key [join [lrange [split $::env(IOLAT_PV_KEY) "_"] end-1 end] "_"]
set _bud_fh [open $::env(IOBUD_TABLE) r]
set _bud_found 0
foreach _bud_line [split [read $_bud_fh] "\\n"] {
  if {[string match "#*" $_bud_line] || [string trim $_bud_line] eq ""} { continue }
  lassign [split $_bud_line "\\t"] _bud_rc _bud_lib _bud_grp _bud_val
  if {"${_bud_rc}_${_bud_lib}" eq $_bud_key} { set _bud($_bud_grp) $_bud_val; incr _bud_found }
}
close $_bud_fh
foreach _bud_g {%(groups)s} {
  if {![info exists _bud($_bud_g)]} { error "IOBUD: no table row for $_bud_key group $_bud_g in $::env(IOBUD_TABLE)" }
}
set _bud_echo "IOBUD key=$_bud_key"
foreach _bud_g {%(groups)s} { append _bud_echo " $_bud_g=$_bud($_bud_g)" }
puts $_bud_echo
"""


def main():
    raw = open(SRC, "rb").read()
    md5 = hashlib.md5(raw).hexdigest()
    if md5 != SRC_MD5:
        sys.exit(f"FATAL: source SDC md5 {md5} != expected {SRC_MD5}; refusing to generate")
    lines = raw.decode().splitlines()
    out = []
    n_rep = 0
    inserted = False
    pat = re.compile(r"^set_input_delay -clock clk_io -max (\d+(?:\.\d+)?) \[get_ports (.+)\]\s*$")
    seen = set()
    for line in lines:
        m = pat.match(line)
        if m:
            port = m.group(2)
            g = dict(GROUPS).get(port)
            assert g, f"unmapped input-delay port {port}"
            line = f"set_input_delay -clock clk_io -max $_bud({g}) [get_ports {port}]"
            n_rep += 1
            seen.add(g)
        out.append(line)
        if line.strip() == "set_clock_uncertainty -hold  0.2 [get_clocks clk_io]":
            assert not inserted
            out += (BUD_BLOCK % {"groups": " ".join(GNAMES)}).splitlines()
            inserted = True
    assert inserted, "anchor not found"
    assert n_rep == 14 and seen == set(GNAMES), f"rewrote {n_rep} lines, groups {sorted(seen)}"
    # drop the source header (its own GENERATED_MD5 lines) and put ours
    start = next(i for i, l in enumerate(out) if l.startswith("# sky130_cpu.sdc") or l.startswith("#============================================="))
    # keep the shared-SDC body starting at the first '#=====' line after the source's own header block
    body_i = None
    for i, l in enumerate(out):
        if l.startswith("# rewritten I/O delays"):
            body_i = i + 2  # skip the closing ===== line
            break
    assert body_i is not None
    body = "\n".join(out[body_i:]) + "\n"

    def render(tag_md5):
        return HEADER + f"{MD5_TAG}{tag_md5}\n" + f"# rewritten: {n_rep} set_input_delay -max groups (table-driven); everything else as the source\n#=============================================================================\n" + body

    wo = "\n".join(l for l in render("").splitlines() if not l.startswith(MD5_TAG)) + "\n"
    excl = hashlib.md5(wo.encode()).hexdigest()
    final = render(excl)
    with open(OUT, "w") as f:
        f.write(final)
    full = hashlib.md5(final.encode()).hexdigest()
    with open(OUT + ".md5", "w") as f:
        f.write(full + "\n")
    print(f"wrote {OUT}\nrewritten: {n_rep} set_input_delay -max lines\nmd5 (full file, sidecar .md5): {full}\nmd5 (without the {MD5_TAG.strip()} line): {excl}")


if __name__ == "__main__":
    main()
