#!/usr/bin/env python3 -I
"""gen_innovus_io_sdc.py -- Innovus b5h constraint files: the shared SDC + a SYMMETRIC, SDC-VISIBLE I/O clock latency (virtual clock clk_io).

Usage:  python3 -I pnr/commercial/constraints/gen_innovus_io_sdc.py <latency_ns> <out.sdc> [--propagated]
Source: pnr/sky130/cpu/constraints/sky130_cpu.sdc (md5 3c69635042a9d65cb87e71a9db713e4e asserted; the source is NEVER modified).
Same construction as gen_iolat_sdc.py / sky130_cpu_iolat.sdc (virtual clk_io, source latency 1.0 mirroring clk_i, network latency <latency_ns>, uncertainty as clk_i,
every set_input_delay/set_output_delay re-referenced to clk_io, group_path IO), but the latency is a PARAMETER: for Innovus b5h it is the measured mean clock-tree
insertion delay of clk_i after CTS (pre-CTS the clocks are ideal, so latency 0.0 is the consistent value).  Replaces Innovus' hidden 'update_io_latency'
(`set_ccopt_property update_io_latency false`), which wrote an asymmetric set_clock_latency into the view's latency.sdc that write_sdc never exported.
--propagated appends `set_propagated_clock [get_clocks clk_i]` (post-CTS file); clk_io stays an IDEAL virtual clock (a propagated virtual clock ignores its network latency).
Deterministic: no timestamps.
"""
import hashlib, os, re, sys

SRC = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../sky130/cpu/constraints/sky130_cpu.sdc"))
SRC_MD5 = "3c69635042a9d65cb87e71a9db713e4e"


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    prop = "--propagated" in sys.argv
    lat, out_path = args[0], args[1]
    float(lat)
    raw = open(SRC, "rb").read()
    if hashlib.md5(raw).hexdigest() != SRC_MD5:
        sys.exit("FATAL: source SDC md5 mismatch")
    out, n_in, n_out, ic, ig = [], 0, 0, False, False
    pat = re.compile(r"^(set_input_delay|set_output_delay)(\s+)-clock\s+clk_i\b")
    for line in raw.decode().splitlines():
        m = pat.match(line)
        if m:
            line = line.replace("-clock clk_i", "-clock clk_io", 1)
            n_in += m.group(1) == "set_input_delay"
            n_out += m.group(1) == "set_output_delay"
        out.append(line)
        if line.strip() == "set_clock_latency -source 1.0 [get_clocks clk_i]":
            out += ["", "# --- I/O clock: virtual, IDEAL (symmetric, SDC-visible replacement of Innovus' hidden update_io_latency) ---",
                    "create_clock -name clk_io -period 13.333",
                    "set_clock_latency -source 1.0 [get_clocks clk_io]",
                    f"set_clock_latency {lat} [get_clocks clk_io]",
                    "set_clock_uncertainty        0.5 [get_clocks clk_io]",
                    "set_clock_uncertainty -hold  0.2 [get_clocks clk_io]"]
            ic = True
        if line.strip() == "group_path -name PIPELINE -from [get_clocks clk_i] -to [get_clocks clk_i]":
            out += ["# I/O paths leave the clk_i->clk_i group", "group_path -name IO -from [get_clocks clk_io]", "group_path -name IO -to   [get_clocks clk_io]"]
            ig = True
    assert ic and ig and n_in == 28 and n_out == 38, (ic, ig, n_in, n_out)
    if prop:
        out += ["", "# post-CTS: the real clock is propagated; clk_io is deliberately NOT", "set_propagated_clock [get_clocks clk_i]"]
    hdr = (f"# sky130_cpu_innovus_io.sdc -- GENERATED by pnr/commercial/constraints/gen_innovus_io_sdc.py (latency {lat} ns, propagated={prop}); do not edit.\n"
           f"# = shared sky130_cpu.sdc (md5 {SRC_MD5}) + virtual I/O clock clk_io with symmetric network latency; all 28 set_input_delay + 38 set_output_delay re-referenced to clk_io.\n")
    open(out_path, "w").write(hdr + "\n".join(out) + "\n")
    print(out_path, hashlib.md5(open(out_path, "rb").read()).hexdigest())


main()
