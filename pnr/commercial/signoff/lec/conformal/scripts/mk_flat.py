#!/usr/bin/env python3
"""mk_flat.py <scripts/lec_genus.do> <out.do>   -- B4b: flat RTL-vs-fv_map compare derived from the Genus do-file.
Keeps Genus' leg-2 setup verbatim (library reads, naming rules, hdl options, RTL read with defines, flatten options, mapping file) and
replaces `write_hier_compare_dofile/run_hier_compare` (hierarchical compare with extracted module-boundary constants) by one flat compare,
so no module-boundary constraint can hide a difference, and the unreachable/unmapped points can be listed."""
import sys
src, dst = sys.argv[1:3]
t = open(src).read()
a = t.index("# Comparing RTL vs. intermediate 'fv_map' netlist.")
b = t.index("write_hier_compare_dofile")
header = t[:t.index("set_mapping_method -sensitive")]
tail = open(__file__.replace("mk_flat.py", "flat_tail.tcl")).read()
assert header.startswith("tclmode\n")  # first line must stay `tclmode`: a leading comment line aborts the do-file
open(dst, "w").write("tclmode\n# [B4b-flat] generated by scripts/mk_flat.py from lec_genus.do\n" + header[len("tclmode\n"):] + "set_mapping_method -sensitive\n\n" + t[a:b] + tail)
print("wrote", dst)
