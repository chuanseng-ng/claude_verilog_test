#!/usr/bin/env python3
"""mk_direct.py <scripts/lec_genus.do> <out.do>  -- B4b: DIRECT flat compare, RTL (golden) vs the FINAL Genus netlist (revised).
Genus' flow goes RTL -> fv_map -> final netlist and feeds LEC Genus' own 'implementation information' (sequential constants,
merges, unreachable flops, boundary optimisations).  This variant drops ALL of that (no read_implementation_information, no
set_verification_information) and keeps only (a) the RTL read/defines/naming rules exactly as Genus wrote them and (b) a pure
NAME mapping file ($env(MAPFILE) = Genus' fv_map->final composed mapping, which only pairs names; a wrong pair can only
cause a mismatch, never hide one).  Constants/merges are then found by Conformal's own analysis (-seq_constant / -seq_merge),
so Genus' claims are not trusted.
  D1 revised design = $env(IMPL) final netlist instead of fv_map.v.gz
  D2 mapping file   = $env(MAPFILE) instead of fv/.../fv_map.map.do
  D3 flatten opts   = + -seq_merge (LEC finds equivalent registers itself, replacing Genus' 108 merge groups)"""
import sys
src, dst = sys.argv[1:3]
t = open(src).read()
a = t.index("# Comparing RTL vs. intermediate 'fv_map' netlist.")
b = t.index("write_hier_compare_dofile")
header = t[:t.index("set_mapping_method -sensitive")]
leg = t[a:b]
def sub(old, new, n=1):
    global leg
    assert leg.count(old) == n, (old, leg.count(old))
    leg = leg.replace(old, new)
sub("set_verification_information rtl_fv_map_db\n\n", "")
sub("read_implementation_information fv/rv32i_cpu_top -revised fv_map -use_rtl_names\n", "# [D0] no read_implementation_information: Genus' constants/merges/unreachable claims are NOT used\n")
sub("read_design -verilog95   -revised -lastmod -noelab fv/rv32i_cpu_top/fv_map.v.gz",
    "# [D1] revised = the FINAL netlist (or a negative-control mutant of it)\nread_design -verilog95   -revised -lastmod -noelab $env(IMPL)")
sub("set_analyze_option -mapping_file fv/rv32i_cpu_top/fv_map.map.do", "# [D2] pure name mapping, composed RTL->final by Genus' analyze_extended_mapping in leg 1\nset_analyze_option -mapping_file $env(MAPFILE)")
sub("write_design -golden rtl_fv_map_db/elab.v -replace", "# [D0] the verification-information db dir is not created without set_verification_information\nfile mkdir rtl_fv_map_db\nwrite_design -golden rtl_fv_map_db/elab.v -replace")
sub("set_flatten_model -hier_seq_merge\n", "set_flatten_model -hier_seq_merge\n# [D3] let LEC discover equivalent (merged) registers itself\nset_flatten_model -seq_merge\n")
# check_verification_information needs the verification-information db that we no longer set
sub("    check_verification_information\n", "    # [D0] check_verification_information skipped (no verification information in the direct run)\n")
tail = open(__file__.replace("mk_direct.py", "flat_tail.tcl")).read().replace("B4B_FLAT_", "B4B_DIRECT_")
assert header.startswith("tclmode\n")
open(dst, "w").write("tclmode\n# [B4b-direct] generated by scripts/mk_direct.py from lec_genus.do\n" + header[len("tclmode\n"):] + "set_mapping_method -sensitive\n\n" + leg + tail)
print("wrote", dst)
