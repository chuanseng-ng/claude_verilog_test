#!/bin/bash
# gen_cmd.sh <arm> <corner> [outdir]   -- write the StarRC command file for one (arm, corner).
# IDENTICAL settings for every arm and corner; only DEF, nxtgrd and output paths differ.
set -eu
arm=$1; corner=$2
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../../../../.." && pwd)
. "$HERE/arms.sh"
. "$ROOT/tools/eda/pd_env.sh" >/dev/null 2>&1 || true
out=${3:-$ROOT/pnr/commercial/signoff/starrc/runs/${arm}_${corner}}
mkdir -p "$out"
PDKB=$ROOT/pnr/commercial/pdk/sky130/build
case $corner in nom) TLEF=$SKY130_HD_TLEF ;; min) TLEF=$SKY130_HD_TLEF_MIN ;; max) TLEF=$SKY130_HD_TLEF_MAX ;; *) exit 2 ;; esac
cat > "$out/starrc.cmd" <<CMD
* StarRC command file, generated by gen_cmd.sh (arm=$arm corner=$corner).  Same for every arm.
BLOCK: rv32i_cpu_top
TCAD_GRD_FILE: $PDKB/nxtgrd/$corner/sky130A_$corner.nxtgrd
MAPPING_FILE: $out/sky130.map
LEF_FILE: $TLEF
LEF_FILE: $SKY130_HD_LEF
LEF_FILE: $SKY130_HD/lef/sky130_ef_sc_hd.lef
LEF_FILE: $SKY130_SRAM_1K_LEF
LEF_FILE: $HERE/icc2_via_names.lef
TOP_DEF_FILE: $ROOT/$(arm_def "$arm")
STAR_DIRECTORY: $out/star
EXTRACTION: RC
COUPLE_TO_GROUND: NO
REDUCTION: NO_EXTRA_LOOPS
OPERATING_TEMPERATURE: 25
NETS: *
POWER_EXTRACT: NO
NETLIST_FORMAT: SPEF
NETLIST_FILE: $out/rv32i_cpu_top.$corner.spef
SHORTS_LIMIT: 1000000
NUM_CORES: ${STARRC_CORES:-2}
CMD
grep -v "^#" "$PDKB/tech/map/starrc_layer.map" > "$out/sky130.map"   # StarRC rejects # comment lines in the mapping file (SX-1907)
echo "$out/starrc.cmd"
