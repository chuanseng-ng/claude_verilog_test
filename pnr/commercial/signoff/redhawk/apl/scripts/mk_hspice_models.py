#!/usr/bin/env python3
"""mk_hspice_models.py <outdir> -- build an HSPICE-readable TT model library for the Sky130 hd standard cells from the open_pdks ngspice files.

Why: the PDK ships ngspice-style models (braces {expr}, `.param` defaults inside .subckt, `.option scale=1.0u`).  HSPICE (the simulator APL can drive,
APL_HSPICE) rejects the braces and does not let instance parameters override `.param` defaults that are not on the .subckt line.  This script makes only
those syntactic conversions (braces, subckt params, AGAUSS(..)*MC_MM_SWITCH with MC_MM_SWITCH=0 -> 0); no model value is touched.
Output: <outdir>/sky130_tt_hspice.lib  with a  `.lib TT ... .endl TT`  section (what APL's DEVICE_MODEL_LIBRARY <file> TT expects),
        containing only the devices the hd cells use: nfet_01v8 and pfet_01v8_hvt (+ their special_* wrappers).
Source files (open_pdks 0fe599b2, sky130A): libs.tech/ngspice/{all.spice (params), parameters/lod.spice}, libs.ref/sky130_fd_pr/spice/
        sky130_fd_pr__{nfet_01v8,pfet_01v8_hvt}__{tt.pm3,mismatch.corner}.spice.   Corner = typical (tt), 25 C, mismatch OFF (mc_mm_switch=0).
"""
import os, re, sys
out = sys.argv[1]
os.makedirs(out, exist_ok=True)
pdk = os.environ.get("SKY130A", os.path.expanduser("~/pdk/ciel/sky130/versions/0fe599b2afb6708d281543108caf8310912f54af/sky130A"))
T = pdk + "/libs.tech/ngspice"; R = pdk + "/libs.ref/sky130_fd_pr/spice"

def conv(txt):
    txt = re.sub(r"\{([^{}]*)\}", lambda m: "'" + m.group(1).strip() + "'", txt)           # {expr} -> 'expr'
    # HSPICE forbids AGAUSS() inside expressions; every use is multiplied by MC_MM_SWITCH (= 0 here, mismatch OFF), so the term is exactly 0 -> literal 0
    txt = re.sub(r"AGAUSS\([^()]*\)", "0", txt, flags=re.I)
    # `.subckt name nodes \n+ \n.param a = 1 b = 2 ...`  ->  `.subckt name nodes a=1 b=2 ...`
    def sub(m):
        params = re.sub(r"\s*=\s*", "=", m.group(3).strip())
        return ".subckt %s %s %s\n" % (m.group(1), m.group(2).strip(), params)
    txt = re.sub(r"^\.subckt\s+(\S+)\s+([^\n]*)\n\+[ \t]*\n\.param\s+([^\n]*)\n", sub, txt, flags=re.M)
    # `.option scale=1.0u` (ngspice) scales the MOS geometry; HSPICE did not scale W through the subckt parameter pass-through (width read as 1.0 m), so the
    # unit scaling is written out explicitly on the model-owning MOS instance: l,w,sa,sb,sd,pd,ps x 1e-6 (um -> m), ad,as x 1e-12 (um2 -> m2); nf, nrd, nrs, mult unscaled.
    sc = {"l": "1e-6", "w": "1e-6", "sa": "1e-6", "sb": "1e-6", "sd": "1e-6", "pd": "1e-6", "ps": "1e-6", "ad": "1e-12", "as": "1e-12"}
    def mos(m):
        line = m.group(0)
        for k, f in sc.items():
            line = re.sub(r"\b%s\s*=\s*'%s'" % (k, k), "%s='%s*%s'" % (k, k, f), line)
        return line
    txt = re.sub(r"^msky130_fd_pr__[^\n]*\n", mos, txt, flags=re.M)
    return txt

def rd(p):
    with open(p) as f: return f.read()

parts = []
parts.append("* HSPICE conversion of the open_pdks sky130A TT models (hd std-cell devices only). Generated by mk_hspice_models.py; values untouched.")
parts.append(".lib TT")
parts.append(".param mc_mm_switch=0 mc_pr_switch=0")
# lod.spice + the *_dlc_rotweak params block of all.spice (lines between `.param` and the first non-continuation line)
parts.append(conv(rd(T + "/parameters/lod.spice")))
al = rd(T + "/all.spice").splitlines()
i = next(k for k, l in enumerate(al) if l.startswith(".param") and l.strip() == ".param")
blk = [al[i]]
for l in al[i + 1:]:
    if l.startswith("+"): blk.append(l)
    else: break
parts.append("\n".join(blk))
for dev in ("nfet_01v8", "pfet_01v8_hvt"):
    parts.append(conv(rd("%s/sky130_fd_pr__%s__mismatch.corner.spice" % (R, dev))))
    parts.append(conv(rd("%s/sky130_fd_pr__%s__tt.pm3.spice" % (R, dev))))
parts.append(".endl TT")
open(out + "/sky130_tt_hspice.lib", "w").write("\n".join(parts) + "\n")
print("wrote", out + "/sky130_tt_hspice.lib")
