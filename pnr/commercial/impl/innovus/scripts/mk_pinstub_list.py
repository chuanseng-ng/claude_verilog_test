#!/usr/bin/env python3 -I
"""mk_pinstub_list.py <kdrc.xml> <def> <out.tcl> -- KLayout m3.6 (met3 island < min area) hits at die-edge I/O pins -> Innovus create_shape list.
Each hit is the lone met3 via pad of a met2 stub ending at a met3 pin (the pin rectangle itself is pin-purpose in the GDS, so the drawn metal is the 0.33 x 0.33 pad only, 0.109 um2 < 0.24).
Fix: a met3 rectangle of the pad's width from the pad to the die edge on the pin's net.  Matching hit -> pin by side (x near 0 or 3600) and |y - pin y| < 0.31 in the DEF PINS section."""
import re, sys
xml, deff, out = sys.argv[1:4]
t = open(xml).read(); hits = []
for it in re.findall(r'<item>(.*?)</item>', t, re.S):
    if "m3.6" not in re.search(r"<category>(.*?)</category>", it).group(1): continue
    v = re.search(r'<value>polygon: (.*?)</value>', it).group(1)
    pts = [tuple(map(float, p.split(','))) for p in v.strip('()').split(';')]
    xs = [p[0] for p in pts]; ys = [p[1] for p in pts]; hits.append((min(xs), min(ys), max(xs), max(ys)))
pins = []; cur = None; sec = False
for l in open(deff):
    if l.startswith('PINS'): sec = True; continue
    if l.startswith('END PINS'): break
    if not sec: continue
    m = re.match(r'- (\S+) \+ NET', l)
    if m: cur = m.group(1)
    m = re.search(r'\+ (?:FIXED|PLACED) \( (-?\d+) (-?\d+) \)', l)
    if m and cur: pins.append((cur, int(m.group(1)) / 1000.0, int(m.group(2)) / 1000.0)); cur = None
lines = []; miss = 0
for (x0, y0, x1, y1) in sorted(hits, key=lambda h: (h[0] > 1800, h[1])):
    yc = (y0 + y1) / 2; east = x0 > 1800
    cand = [p for p in pins if (p[1] > 1800) == east and abs(p[2] - yc) < 0.31]
    if len(cand) != 1: miss += 1; print("NO UNIQUE PIN for hit", (x0, y0, x1, y1), cand); continue
    # rectangle: pad column (>= 0.30 wide, min width met3) from the pad to the die edge
    yl = round(yc - 0.165, 3); yh = round(yc + 0.165, 3)
    xa, xb = (round(x0, 3), 3600.0) if east else (0.0, round(x1, 3))
    lines.append("  {%s %s %s %s %s %s}" % (cand[0][0], xa, yl, xb, yh, "E" if east else "W"))
open(out, "w").write("# generated by mk_pinstub_list.py from the b5j KLayout m3.6 hits: {net x0 y0 x1 y1 side}\nset B5K_STUBS {\n" + "\n".join(lines) + "\n}\n")
print(len(hits), "hits,", len(lines), "stubs,", miss, "unmatched")
