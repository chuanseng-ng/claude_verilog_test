#!/usr/bin/env python3 -I
"""ant_to_pins.py <check_antennas -verbose report> <out.tcl> -- list the gate pins that OpenROAD check_antennas (the signoff-deck stand-in) marks (VIOLATED) as `set PINS {{inst pin} ...}` for the Innovus
attachDiode antenna ECO (05m_eco.tcl).  Pin lines look like `  Pin:   u_core/g45325/C2 (sky130_fd_sc_hd__a22o_1)`; the instance name keeps its escaped brackets (Innovus syntax); DIODE pins are skipped."""
import re, sys
pins, cur, viol = [], None, False
def flush():
    global cur, viol
    if cur and viol and not cur.endswith("/DIODE"): pins.append(cur)
    cur, viol = None, False
for l in open(sys.argv[1]):
    m = re.match(r"\s+Pin:\s+(\S+)\s+\(", l)
    if m: flush(); cur = m.group(1); continue
    if l.startswith("Net:"): flush(); continue
    if "(VIOLATED)" in l: viol = True
flush()
out = []
for p in dict.fromkeys(pins):
    i, _, pin = p.rpartition("/")
    out.append(" {%s %s}" % (i, pin))
open(sys.argv[2], "w").write("# generated by ant_to_pins.py from %s\nset PINS [list \\\n%s]\n" % (sys.argv[1], " \\\n".join(out)))
print(len(out), "violating pins ->", sys.argv[2])
