#!/usr/bin/env python3
# ruff: noqa: E501
"""Create simulation stand-ins for the two black-box macro types of the SoC fabric netlist.

ATPG treats rv32i_cpu_top and the SRAM macro as black boxes whose outputs are X, and Tessent's expected responses mask
every observe point that depends on them.  For the VCS pattern check the same behaviour is reproduced: every output of the
stand-in is driven to X.  Port lists come from the instantiations in the gate netlist (name, direction and width are taken
from the committed black-box stubs via yosys `write_verilog -blackboxes` output passed in).
Usage: mk_sim_stubs.py <blackbox_ports.v> <out.v>
"""
import re
import sys

src = open(sys.argv[1]).read()
out = ["// Simulation stand-ins (outputs = X) for the black-box macros; generated by mk_sim_stubs.py"]
for m in re.finditer(r"module\s+(\\?\S+)\s*\((.*?)\);(.*?)endmodule", src, re.S):
    name, ports, body = m.group(1), m.group(2), m.group(3)
    decls = re.findall(r"^\s*(input|output)\s*(\[[^\]]+\])?\s*(\S+?)\s*;", body, re.M)
    if not decls:
        continue
    out.append("module %s (%s);" % (name, ", ".join(d[2] for d in decls)))
    for d, rng, p in decls:
        out.append("  %s %s %s;" % (d, rng, p))
    for d, rng, p in decls:
        if d == "output":
            w = re.match(r"\[(\d+):(\d+)\]", rng) if rng else None
            n = abs(int(w.group(1)) - int(w.group(2))) + 1 if w else 1
            out.append("  assign %s = {%d{1'bx}};" % (p, n))
    out.append("endmodule")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print("mk_sim_stubs: wrote", sys.argv[2])
